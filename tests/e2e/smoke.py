# Browser-Rauchtest (optional): Produktions-Build in Chromium mit iPhone-Viewport.
# Voraussetzungen: npm run build, Python 3 + `pip install playwright` + `playwright install chromium`
# Start im Projektordner:  python tests/e2e/smoke.py
import subprocess, time, json, sys, os, re, tempfile
from playwright.sync_api import sync_playwright
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..'))
SHOTS=os.path.join(tempfile.gettempdir(),'wakelog-shots'); os.makedirs(SHOTS,exist_ok=True)
srv=subprocess.Popen(['npx','vite','preview','--port','4173','--strictPort'],cwd=ROOT,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
time.sleep(2.5)
URL='http://localhost:4173/'
results=[]; errors=[]
def check(name, cond):
    results.append((name, bool(cond))); print(('PASS ' if cond else 'FAIL ')+name)
def noscroll(page, label):
    w=page.evaluate('[document.documentElement.scrollWidth, window.innerWidth]')
    check(f'kein horizontales Scrollen: {label} {w}', w[0]<=w[1])
try:
  with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True,locale='de-DE',timezone_id='Europe/Berlin',color_scheme='light')
    page=ctx.new_page()
    page.on('console', lambda m: m.type=='error' and errors.append(m.text))
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(URL); page.wait_for_selector('.night-card')
    check('Heute-Ansicht lädt', page.locator('h1').inner_text()=='Heute')
    page.screenshot(path=SHOTS+'/01_heute_leer_hell.png')
    noscroll(page,'Heute leer')
    # --- Aufwachen eintragen (Standard: jetzt) mit eigener Zeit
    page.get_by_role('button', name='Aufwachen eintragen').click()
    page.wait_for_selector('dialog.sheet')
    page.screenshot(path=SHOTS+'/02_formular.png')
    # Ohne Auswahl speichern -> Fehlermeldung
    page.locator('dialog .sheet-footer .btn-primary').click()
    check('Formularfehler ohne Verhalten', page.locator('dialog .field-error').count()>0)
    page.fill('dialog input[type=date]','2026-10-16'); page.fill('dialog input[type=time]','03:37')
    page.locator('label.outcome-option', has_text='Wieder eingeschlafen').click()
    page.fill('dialog textarea','Straße laut; "Müllabfuhr"')
    check('Zuordnungshinweis zeigt Nacht 15.10.', '15.10.' in page.locator('dialog .field-hint').first.inner_text())
    page.locator('dialog .sheet-footer .btn-primary').click()
    page.wait_for_selector('dialog.sheet', state='detached')
    check('Ereignis in Timeline', page.locator('.tl-event').count()==1)
    # zweites Ereignis gleiche Minute gleicher Ausgang -> Duplikatwarnung
    page.get_by_role('button', name='Aufwachen eintragen').click()
    page.fill('dialog input[type=date]','2026-10-16'); page.fill('dialog input[type=time]','03:37')
    page.locator('label.outcome-option', has_text='Wieder eingeschlafen').click()
    page.locator('dialog .sheet-footer .btn-primary').click()
    check('Duplikatwarnung', page.locator('dialog .notice-warning').count()==1)
    page.get_by_role('button', name='Schließen', exact=True).click()
    # Ereignis 23:50 am Vorabend
    page.get_by_role('button', name='Aufwachen eintragen').click()
    page.fill('dialog input[type=date]','2026-10-15'); page.fill('dialog input[type=time]','23:50')
    page.locator('label.outcome-option', has_text='Noch unbekannt').click()
    page.locator('dialog .sheet-footer .btn-primary').click()
    page.wait_for_selector('dialog.sheet', state='detached')
    times=page.locator('.tl-event .tl-time').all_inner_texts()
    check(f'Sortierung über Mitternacht {times}', [t.split('\n')[0] for t in times]==['23:50','03:37'])
    # Aufstehen
    page.get_by_role('button', name='Aufstehen eintragen').click()
    page.fill('dialog input[type=date]','2026-10-16'); page.fill('dialog input[type=time]','06:15')
    page.locator('dialog .sheet-footer .btn-primary').click()
    page.wait_for_selector('dialog.sheet', state='detached')
    check('Aufstehzeit 06:15 angezeigt', '06:15' in page.locator('.night-stats').inner_text())
    page.screenshot(path=SHOTS+'/03_heute_hell.png', full_page=True)
    # Bearbeiten: Ereignis 03:37 -> 03:41
    page.locator('.tl-event').nth(1).locator('button').click()
    page.fill('dialog input[type=time]','03:41')
    page.locator('dialog .sheet-footer .btn-primary').click()
    page.wait_for_selector('dialog.sheet', state='detached')
    check('Bearbeiten übernommen', '03:41' in page.locator('.timeline').inner_text())
    # --- Persistenz nach Reload
    page.reload(); page.wait_for_selector('.night-card')
    check('IndexedDB: Daten nach Reload vorhanden', page.locator('.tl-event').count()==2 and '06:15' in page.locator('.night-stats').inner_text())
    # Löschen eines Ereignisses
    page.locator('.tl-event').first.locator('button').click()
    page.get_by_role('button', name='Ereignis löschen').click()
    page.locator('dialog[role=alertdialog] .btn-danger').click()
    page.wait_for_function('document.querySelectorAll("dialog").length===0')
    check('Löschen eines Ereignisses', page.locator('.tl-event').count()==1)
    # --- Import Beispieldaten (Zusammenführen)
    page.goto(URL+'#/einstellungen'); page.wait_for_selector('.settings')
    page.set_input_files('input[type=file]',os.path.join(ROOT,'beispieldaten','wakelog-beispieldaten.json'))
    page.wait_for_selector('dialog.sheet')
    page.screenshot(path=SHOTS+'/04_import.png')
    page.locator('dialog .sheet-footer .btn-primary').click()
    page.wait_for_selector('dialog.sheet', state='detached')
    txt=page.locator('.settings').inner_text()
    check('Import zusammengeführt (53 Nächte)', '53 Nächte' in txt)
    # --- JSON-Export (Download)
    with page.expect_download() as dl:
        page.get_by_role('button', name='JSON exportieren').click()
    path=dl.value.path(); exp=json.load(open(path))
    check(f'JSON-Export enthält {len(exp["episodes"])} Nächte', len(exp['episodes'])==53 and exp['format']=='wakelog-backup')
    with page.expect_download() as dl2:
        page.get_by_role('button', name='CSV exportieren').click()
    csv=open(dl2.value.path(),encoding='utf-8-sig').read()
    check('CSV-Export mit Umlauten & Escaping', 'Straße laut; ""Müllabfuhr""' in csv and csv.startswith('Nacht (Beginn);'))
    # --- Kalender
    page.get_by_role('button', name='Kalender').click(); page.wait_for_selector('.calendar')
    check('Kalender markiert dokumentierte Tage', page.locator('.cal-cell.doc-one, .cal-cell.doc-many, .cal-cell.doc-zero').count()>10)
    noscroll(page,'Kalender')
    page.screenshot(path=SHOTS+'/05_kalender_hell.png', full_page=True)
    page.get_by_role('button', name='Vorheriger Monat').click()
    check('Monatswechsel', 'September 2026' in page.locator('.cal-head h2').inner_text())
    page.locator('.cal-cell.doc-many').first.click()
    check('Tag auswählen öffnet Nacht', page.locator('.tl-event').count()>=2)
    page.get_by_role('button', name='Zur aktuellen Nacht').click()
    check('Zur aktuellen Nacht', 'Oktober 2026' in page.locator('.cal-head h2').inner_text())
    # --- Statistik
    page.get_by_role('button', name='Statistik').click(); page.wait_for_selector('.tiles')
    noscroll(page,'Statistik')
    page.screenshot(path=SHOTS+'/06_statistik_hell.png', full_page=True)
    page.locator('label.seg', has_text='Alle').click()
    s1=page.locator('.chart').first.locator('rect.chart-bar').count()
    page.locator('label.seg', has_text='60 min').click()
    s2=page.locator('.chart').first.locator('rect.chart-bar').count()
    check(f'Intervallgröße verändert Verteilung ({s1}→{s2} Säulen)', s1!=s2)
    page.locator('label.seg').filter(has_text=__import__('re').compile(r'^5 min$')).click()
    noscroll(page,'Statistik 5 min')
    # --- Theme: Dunkel, Persistenz
    page.get_by_role('button', name='Einstellungen').click(); page.wait_for_selector('.settings')
    page.locator('label.seg', has_text='Dunkel').click()
    check('Theme sofort dunkel', page.evaluate('document.documentElement.dataset.theme')=='dark')
    page.screenshot(path=SHOTS+'/07_einstellungen_dunkel.png', full_page=True)
    page.reload(); page.wait_for_selector('.settings')
    check('Theme nach Neustart erhalten', page.evaluate('document.documentElement.dataset.theme')=='dark')
    for r,name in [('heute','08_heute_dunkel'),('kalender','09_kalender_dunkel'),('statistik','10_statistik_dunkel')]:
        page.goto(URL+'#/'+r); page.wait_for_timeout(400)
        page.screenshot(path=f'{SHOTS}/{name}.png', full_page=True)
    page.goto(URL+'#/heute'); page.wait_for_selector('.night-card')
    page.get_by_role('button', name='Aufwachen eintragen').click()
    page.screenshot(path=SHOTS+'/11_formular_dunkel.png')
    page.get_by_role('button', name='Schließen', exact=True).click()
    # System-Modus folgt Systemeinstellung
    page.goto(URL+'#/einstellungen'); page.locator('label.seg', has_text='System').click()
    page.emulate_media(color_scheme='dark'); page.wait_for_timeout(100)
    d1=page.evaluate('document.documentElement.dataset.theme')
    page.emulate_media(color_scheme='light'); page.wait_for_timeout(100)
    d2=page.evaluate('document.documentElement.dataset.theme')
    check(f'System-Modus folgt Systemwechsel ({d1}/{d2})', d1=='dark' and d2=='light')
    # --- Offline-Start über Service Worker
    page.goto(URL); page.wait_for_function('navigator.serviceWorker.controller !== null', timeout=10000)
    check('Service Worker steuert Seite', True)
    ctx.set_offline(True)
    page.reload(); page.wait_for_selector('.night-card', timeout=8000)
    check('Offline-Start inkl. Daten', page.locator('.tl-event').count()>=1)
    page.goto(URL+'#/statistik'); page.wait_for_selector('.tiles')
    check('Statistik offline', True)
    ctx.set_offline(False)
    # --- Alle Daten löschen
    page.goto(URL+'#/einstellungen'); page.wait_for_selector('.settings')
    page.get_by_role('button', name='Alle lokalen Daten löschen').click()
    page.locator('dialog[role=alertdialog] .btn-danger').click()
    check('Löschen ohne Bestätigungswort blockiert', page.locator('dialog[role=alertdialog]').count()==1)
    page.fill('dialog[role=alertdialog] input','LÖSCHEN'); page.locator('dialog[role=alertdialog] .btn-danger').click()
    page.wait_for_timeout(300)
    check('Alle Daten gelöscht', '0 Nächte' in page.locator('.settings').inner_text())
    page.goto(URL+'#/statistik'); page.wait_for_selector('.empty')
    page.screenshot(path=SHOTS+'/12_statistik_leer.png')
    # Schmales Display (iPhone SE 320 px)
    ctx2=b.new_context(viewport={'width':320,'height':568},is_mobile=True,has_touch=True,locale='de-DE',timezone_id='Europe/Berlin')
    p2=ctx2.new_page(); p2.goto(URL); p2.wait_for_selector('.night-card')
    noscroll(p2,'320px Heute')
    p2.get_by_role('button', name='Aufwachen eintragen').click(); p2.wait_for_timeout(300)
    noscroll(p2,'320px Formular'); p2.screenshot(path=SHOTS+'/13_se_formular.png')
    b.close()
finally:
    srv.terminate()
print('\nKonsolenfehler:', errors)
print(f"\n{sum(r for _,r in results)}/{len(results)} Prüfungen bestanden · Screenshots: {SHOTS}")
sys.exit(0 if all(r for _,r in results) and not errors else 1)
